/// Filled "users" composite — Tabler has no official `users-filled` icon.
Widget _usersFilled(double s) {
  final person = s * 0.56;
  return SizedBox(
    width: s,
    height: s,
    child: Stack(
      clipBehavior: Clip.hardEdge,
      children: [
        Positioned(
          left: 0,
          bottom: 0,
          child: tabler.UserFilled(width: person, height: person),
        ),
        Positioned(
          right: 0,
          top: s * 0.04,
          child: tabler.UserFilled(width: person, height: person),
        ),
      ],
    ),
  );
}

